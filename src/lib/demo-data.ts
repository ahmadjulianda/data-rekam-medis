/**
 * Data contoh untuk MODE DEMO (dipakai hanya bila env Supabase kosong).
 * Tanggal kunjungan dibuat relatif terhadap hari ini agar dashboard selalu
 * menunjukkan data yang masuk akal. Bukan data pasien sungguhan.
 */

function daysAgo(days: number, hour = 9, minute = 0): string {
  const d = new Date()
  d.setDate(d.getDate() - days)
  d.setHours(hour, minute, 0, 0)
  return d.toISOString()
}

function id(prefix: 'u' | 'p' | 'm' | 'r', n: number): string {
  const hex = n.toString(16).padStart(12, '0')
  return `00000000-0000-4000-8000-${prefix === 'u' ? 'a' : prefix === 'p' ? 'b' : prefix === 'm' ? 'c' : 'd'}${hex.slice(1)}`
}

